    def clear_list(self, remove_pending=...) -> list[str]: ...
    def retry_failed(self, selected=...) -> Any: ...
    def _add_summary_progress(self, value) -> Any: ...
    def _sync_summary_task(self, tid) -> Any: ...
    def register_download_streams(self, tid, streams) -> Any: ...
    def report_stage_progress(self, tid, stage, fraction=..., *, status=..., download_metrics=..., state=...) -> Any: ...
    def begin_task_attempt(self, tid) -> Any: ...
    def task_log_fields(self, tid) -> Any: ...
