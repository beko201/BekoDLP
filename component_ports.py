"""Operation contracts injected into engine and manager components.

These protocols name supported calls without importing concrete facades. The
facades preserve override points while routing calls to their owning services.
"""
from __future__ import annotations
from _thread import LockType
from collections import deque
from contextvars import ContextVar
from queue import Queue
import threading
from typing import Any, Callable, Protocol, TYPE_CHECKING

if TYPE_CHECKING:
    from engine_runtime import EngineRuntime
    from task_runtime import TaskRuntime
    from media_probe import MediaProbeCache
    from network_limits import NetworkLimits
    from processing_limits import ProcessingLimits
    from resolved_info_cache import ResolvedInfoCache
    from task_storage import CancellationEvent, TaskRecord
    from task_types import TaskEventQueue, TaskSummary


class EngineOperations(Protocol):
    runtime: EngineRuntime
    manager: TaskOperations
    ffmpeg: str | None
    ffprobe: str | None
    current_process_pids: dict[int, int]
    managed_processes: set
    _force_stopping: bool
    reserved_output_paths: dict[str, str]
    resource_lock: LockType
    _subtitle_context: dict[str, dict]
    _output_naming: dict[str, tuple]
    _rate_divisor: ContextVar[int]
    _encoder_lock: LockType
    _encoders: frozenset[str] | None
    processing_limits: ProcessingLimits
    network_limits: NetworkLimits
    _probe_cache: ContextVar[MediaProbeCache | None]
    def configure_processing(self, video_workers, ffmpeg_threads) -> Any: ...
    def configure_network(self, fragment_downloads, network_connections) -> Any: ...
    def validate_tools(self) -> Any: ...
    def process_task(self, task_tuple, worker_id: int) -> Any: ...
    def _process_task_attempt(self, task_tuple, worker_id: int) -> Any: ...
    def ytdlp_process(self, options, tid, *, stop_event=..., folder=...) -> Any: ...
    def media_download_session(self, tid, *, streams=..., fragmented=..., stop_event=...) -> Any: ...
    def _wait_for_download_resume(self, tid, *, stop_event=...) -> Any: ...
    def _download_from_info(self, ydl, source_url, media_info, cancel_event, *, format_id=..., stop_event=..., tid=...) -> Any: ...
    def _download_format(self, tid, stream_key, source_url, yt_format, filename, *, folder, stop_event=...) -> Any: ...
    def _download_streams_parallel(self, tid, source_url, video_stream, audio_stream, video_filename, audio_filename, *, folder) -> Any: ...
    def _complete_via_selector(self, tid, worker_id, url, title_safe, raw_title, fmt, target_height, force_h264, trim_start, trim_end, *, folder, output_folder=..., media_info=...) -> Any: ...
    def _complete_via_selector_in_workspace(self, tid, worker_id, url, title_safe, raw_title, fmt, target_height, force_h264, trim_start, trim_end, *, folder, output_folder, media_info=...) -> Any: ...
    def media_probe_session(self, *, new_attempt=...) -> Any: ...
    def _invalidate_media_probes(self, *paths) -> Any: ...
    def _replace_media(self, source, destination) -> Any: ...
    def available_encoders(self) -> frozenset[str]: ...
    def _estimate_mp3_bytes(self, tid, source_bytes) -> Any: ...
    def _check_disk_space(self, folder, required_bytes, *, output_bytes=..., trim_bytes=...) -> Any: ...
    def _check_download_disk_space(self, tid, folder, downloaded, total) -> Any: ...
    def _check_ffmpeg_disk_space(self, tid, cmd, duration=...) -> Any: ...
    def _maybe_trim(self, tid, worker_id, input_path, trim_start_text, trim_end_text) -> str: ...
    @staticmethod
    def _select_merge_container(video_codecs, audio_codecs) -> str: ...
    def _ffprobe_media(self, path, *, fresh=...) -> dict[str, Any]: ...
    def _probe_media(self, path, executable, *, fresh=...) -> dict[str, Any]: ...
    def _read_media_probe(self, path, executable) -> dict[str, Any]: ...
    def _ffprobe_copy_start(self, path, stream_index, requested_start) -> float: ...
    @staticmethod
    def _is_h264_compatible(info) -> bool: ...
    def _ensure_h264_compatible(self, tid, worker_id, path) -> Any: ...
    def _ffprobe_vcodec(self, path) -> Any: ...
    def _ffprobe_duration(self, path, ffprobe_cmd) -> float: ...
    def _ffmpeg_convert_to_mp3(self, tid, worker_id, in_path, out_path) -> Any: ...
    def _task_duration(self, tid) -> float: ...
    def _cleanup_workspace(self, work_dir, parent_folder) -> Any: ...
    def _release_output_reservation(self, path, tid) -> Any: ...
    def _record_subtitle_start(self, tid, start) -> Any: ...
    def _publish_output(self, tid, source, output_folder, *, apply_naming=...) -> str: ...
    def _publish_media_file(self, tid, source, output_folder, *, filename=...) -> str: ...
    def _dedupe_path(self, path, tid) -> str: ...
    def _run_ffmpeg(self, tid, worker_id, cmd, duration=..., status_label=..., *, check=..., progress_stage=..., stop_event=...) -> int: ...
    def _run_ffmpeg_process(self, tid, worker_id, cmd, duration=..., status_label=..., *, check=..., progress_stage=..., stop_event=...) -> Any: ...
    def _register_process(self, proc) -> None: ...
    def _unregister_process(self, proc) -> None: ...
    def terminate_managed_processes(self) -> None: ...
    def _pump_ffmpeg_progress(self, proc, tid, duration, status_label, *, disk_folder=..., progress_stage=..., stop_event=...) -> Any: ...


