    _progress_correction: float
    _action_revision: int
    _queue_revision: int
    _queue_rows: dict[str, tuple]
    _restart_after_shutdown: set[str]
    _restored_queue_paused: bool
    _resolved_info: ResolvedInfoCache
    task_counter: int
    task_queue: Queue
    events: TaskEventQueue
    _compact_task_events: bool
    workers: list[threading.Thread]
    retiring_workers: list[threading.Thread]
    worker_counter: int
    worker_count: int
    background_threads: set[threading.Thread]
    link_queue: Queue
    link_workers: list[threading.Thread]
    _pending_link_keys: set
    paused: bool
    active_urls: set[str]
